#!/usr/bin/env bun
// Generate `docs/cli-reference.md` from the binaries' own help.
//
// The reference used to be written by hand, and it drifted: it documented
// flags that did not exist, missed subcommands that did, and described a
// set of "common commands" that only one binary had. A document that is
// written by hand about commands that are written in Rust is a document
// that goes out of date the day the code changes.
//
// This asks the binaries instead. Their help is the truth about their
// commands, and the reference is a rendering of it.
//
// Usage: bun scripts/generate-cli-reference.ts [--check] [--bin-dir <path>]
//
//   --check       Write nothing; exit non-zero when the file is out of date.
//   --bin-dir     Where the built binaries are. Defaults to the release and
//                 debug directories under `target/`.

import { existsSync } from "bun:fs";
import { join } from "bun:path";

const ROOT = new URL("..", import.meta.url).pathname;
const OUTPUT = join(ROOT, "docs", "cli-reference.md");

/** Where the binaries are, when the caller does not say. */
function defaultBinDirs(): string[] {
  return [join(ROOT, "target", "release"), join(ROOT, "target", "debug")];
}

/** The binaries the reference covers, in the order they are read. */
const BINARIES = [
  ["fs-app", "The cross-platform app tool: hooks, builds, simulators and emulators."],
  ["lefthook-rs", "The git hook tool: secrets, commit messages, bundle size and accessibility."],
  ["foodshare-i18n", "The translation tool: health, audits, translations and deployment."],
  ["foodshare-swift", "The Swift toolchain tool: detect, verify, configure and migrate."],
  ["fs-image", "The image tool: detect, analyse, resize and strip alpha."],
  ["fs-auto", "The headless orchestrator: run until green, build, clean."],
  ["fs-tui", "The live monitor over the same plan."],
  ["fs-orchestrator", "The HTTP daemon over the same plan."],
  ["fs-verify", "The full cross-repository verification."],
  ["fs-maestro", "The Maestro E2E runner."],
  ["fs-wasm", "The WebAssembly build engine."],
  ["fs-build", "The cross-platform build engine."],
  ["fs-sim", "The simulator runner."],
  ["fs-xccloud", "The Xcode Cloud builds, logs and diagnostics."],
  ["foodshare-quadlet", "The Quadlet validator for Podman units."],
];

/** Where the built binaries are. */
function binaryPath(name: string, dirs: string[]): string | null {
  for (const dir of dirs) {
    const path = join(dir, name);
    if (existsSync(path)) return path;
  }
  return null;
}

/** Run a binary and capture its output. */
async function run(path: string, args: string[]): Promise<string> {
  const process = Bun.spawn([path, ...args], { stdout: "pipe", stderr: "pipe" });
  const [stdout, stderr] = await Promise.all([
    new Response(process.stdout).text(),
    new Response(process.stderr).text(),
  ]);
  await process.exited;
  return (stdout + stderr).trimEnd();
}

/** The subcommand names a binary offers, from its help. */
function subcommands(help: string): string[] {
  const names: string[] = [];
  let inCommands = false;

  for (const line of help.split("\n")) {
    if (/^Commands:\s*$/.test(line)) {
      inCommands = true;
      continue;
    }
    if (inCommands) {
      if (/^\S/.test(line) && line.trim() !== "") break;
      const match = line.match(/^\s{2}(\S+)\s/);
      if (match && !match[1].startsWith("-")) names.push(match[1]);
    }
  }

  return names;
}

/** The help of one subcommand, with the parent's own help as a fallback. */
async function subcommandHelp(path: string, name: string): Promise<string> {
  return await run(path, [name, "--help"]);
}

async function render(dirs: string[]): Promise<string> {
  const parts: string[] = [];

  parts.push("# CLI Reference");
  parts.push("");
  parts.push(
    "<!-- Generated by `bun scripts/generate-cli-reference.ts` from the binaries' own",
  );
  parts.push(
    "     help. Run it after changing a command; `bun scripts/generate-cli-reference.ts --check`",
  );
  parts.push(
    "     fails when the reference has fallen behind the code. -->",
  );
  parts.push("");
  parts.push(
    "Every command below is one the binary actually has. The exit codes are the ones",
  );
  parts.push(
    "the `E`-code scheme in the [README](../README.md#error-codes) describes: `0` is",
  );
  parts.push(
    "success, `2` is a validation failure, `3` a configuration failure, `4` a git",
  );
  parts.push(
    "failure, `5` a security failure, `124` a timeout and `127` a command that is not",
  );
  parts.push("installed.");
  parts.push("");

  for (const [name, about] of BINARIES) {
    const path = binaryPath(name, dirs);
    if (!path) {
      parts.push(`## ${name}`);
      parts.push("");
      parts.push(
        "_The binary is not built. Run `cargo build --release` to see it._",
      );
      parts.push("");
      continue;
    }

    const help = await run(path, ["--help"]);
    parts.push(`## ${name}`);
    parts.push("");
    parts.push(about);
    parts.push("");
    parts.push("```");
    parts.push(help);
    parts.push("```");
    parts.push("");

    for (const sub of subcommands(help)) {
      const subHelp = await subcommandHelp(path, sub);
      if (!subHelp) continue;
      parts.push(`### ${name} ${sub}`);
      parts.push("");
      parts.push("```");
      parts.push(subHelp);
      parts.push("```");
      parts.push("");
    }
  }

  return parts.join("\n").replace(/\n{3,}/g, "\n\n") + "\n";
}

const args = Bun.argv.slice(2);
const check = args.includes("--check");
const binDirIndex = args.indexOf("--bin-dir");
const dirs = (
  binDirIndex === -1 ? "" : (args[binDirIndex + 1] ?? "")
)
  .split(",")
  .filter((dir) => dir !== "");
const searchDirs = dirs.length > 0 ? dirs : defaultBinDirs();
const content = await render(searchDirs);

if (check) {
  const current = existsSync(OUTPUT) ? await Bun.file(OUTPUT).text() : "";
  if (current !== content) {
    console.error("❌ docs/cli-reference.md is out of date");
    console.error("   Run: bun scripts/generate-cli-reference.ts");
    process.exit(1);
  }
  console.log("✅ docs/cli-reference.md is up to date");
} else {
  await Bun.write(OUTPUT, content);
  console.log(`✅ wrote ${OUTPUT}`);
}
